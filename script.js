function getPromptSourceKey(prompt) {
  return prompt.source.url || prompt.source.title;
}

function groupPromptsBySource(prompts) {
  const groups = [];
  prompts.forEach((prompt) => {
    const key = getPromptSourceKey(prompt);
    let group = groups.find((item) => item.key === key);
    if (!group) {
      group = {
        key,
        meta: getPromptSourceMeta(prompt),
        prompts: []
      };
      groups.push(group);
    }
    group.prompts.push(prompt);
  });
  return groups;
}

