async function shareContent({ title, text, fallback, successText, copyText }) {
  try {
    if (navigator.share) {
      await navigator.share({
        title,
        text,
        url: window.location.href
      });
      showToast(successText);
      return;
    }

    await navigator.clipboard.writeText(fallback);
    showToast(copyText);
  } catch {
    try {
      await navigator.clipboard.writeText(fallback);
      showToast(copyText);
    } catch {
      showToast(fallback);
    }
  }
}

