async function copyPrompt(prompt) {
  const text = promptToText(prompt);
  try {
    await copyText(text);
    showToast("已复制，请替换红色部分");
  } catch {
    selectPromptText();
    showToast("复制受限，已选中正文");
  }
}

function selectPromptText() {
  const target = document.querySelector(".promptText");
  if (!target || !window.getSelection) return;

  const range = document.createRange();
  range.selectNodeContents(target);
  const selection = window.getSelection();
  selection.removeAllRanges();
  selection.addRange(range);
}

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      // Fall through to the textarea fallback for browsers that block clipboard permissions.
    }
  }

  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.top = "0";
  textarea.style.left = "0";
  textarea.style.width = "1px";
  textarea.style.height = "1px";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  textarea.focus();
  textarea.select();
  textarea.setSelectionRange(0, textarea.value.length);
  const copied = document.execCommand("copy");
  document.body.removeChild(textarea);
  if (!copied) throw new Error("copy failed");
}

function choose(type) {
  state.answers[state.current] = type;
  if (state.current < questions.length - 1) {
    state.current += 1;
    renderQuestion();
  } else {
    renderResult();
    showScreen("result");
  }
}

function getScores() {
  return Object.keys(types).reduce((acc, key) => {
    acc[key] = state.answers.filter((answer) => answer === key).length;
    return acc;
  }, {});
}

function getWinner(scores) {
  const order = ["A", "B", "C", "D", "E"];
  return order.reduce((best, key) => {
    if (scores[key] > scores[best]) return key;
    return best;
  }, "A");
}

function renderResult() {
  const scores = getScores();
  const winner = getWinner(scores);
  const type = types[winner];
  const max = Math.max(...Object.values(scores), 1);

  els.resultMeta.textContent = `${type.name} · ${type.zh}`;
  els.resultTitle.textContent = type.label;
  els.resultSubtitle.textContent = type.short;
  els.resultStrength.textContent = type.strength;
  els.resultRisk.textContent = type.risk;
  els.resultAction.textContent = type.actions.map((action, index) => `${index + 1}. ${action}`).join("\n");
  els.scoreBoard.innerHTML = "";
  Object.entries(types).forEach(([key, item]) => {
    const row = document.createElement("div");
    row.className = "scoreItem";
    row.innerHTML = `
      <span class="scoreName">${item.label}</span>
      <span class="scoreTrack"><span style="width:${(scores[key] / max) * 100}%; background:${item.color}"></span></span>
      <span class="scoreCount">${scores[key]}</span>
    `;
    els.scoreBoard.appendChild(row);
  });

}

