function renderHighlightedPromptText(text, prompt) {
  const placeholders = ["\\{\\{[^}]+\\}\\}", "【[^】]+】", "\\{[^}\\n]+\\}", "\\[[^\\]\\n]*请填入[^\\]\\n]*\\]"];
  const terms = getPromptHighlightTerms(prompt).map(escapeRegExp);
  const pattern = new RegExp(`(${[...terms, ...placeholders].join("|")})`, "g");

  return String(text).split(pattern).map((segment) => {
    if (!segment) return "";
    pattern.lastIndex = 0;
    if (pattern.test(segment)) return `<span class="promptVariable">${escapeHtml(segment)}</span>`;
    return `<span>${escapeHtml(segment)}</span>`;
  }).join("");
}

function renderPromptParts(prompt) {
  return prompt.promptParts.map((part) => {
    if (part.editable) return `<span class="promptVariable">${escapeHtml(part.text)}</span>`;
    return renderHighlightedPromptText(part.text, prompt);
  }).join("");
}

